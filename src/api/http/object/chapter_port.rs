/// Query selecting every format generated by one chapter export.
#[derive(Debug, Deserialize)]
#[cfg_attr(feature = "swagger", derive(ToSchema))]
pub struct ExportChapterTranslationQuery {
    /// Use complete original filenames for `LabelPlus` references when present.
    #[serde(default)]
    #[cfg_attr(feature = "swagger", schema(default = false))]
    pub with_raw_ident: bool,

    /// Comma-separated formats: `poprako`, `label_plus`, or both.
    #[serde(deserialize_with = "deserialize_export_format_spec")]
    pub format: ExportFormatSpec,
}

// Converts the public comma-separated query value into a validated domain spec.
fn deserialize_export_format_spec<'de, D>(
    deserializer: D,
) -> Result<ExportFormatSpec, D::Error>
where
    D: Deserializer<'de>,
{
    let format_names = String::deserialize(deserializer)?;

    let mut label_plus = false;

    let mut poprako = false;

    for format_name in format_names.split(',') {
        //
        match format_name {
            //
            "label_plus" if !label_plus => label_plus = true,

            "poprako" if !poprako => poprako = true,

            "label_plus" | "poprako" => {
                return Err(D::Error::custom("duplicate export format"));
            }

            _ => return Err(D::Error::custom("invalid export format")),
        }
    }

    match (label_plus, poprako) {
        //
        (true, false) => Ok(ExportFormatSpec::LABEL_PLUS),

        (false, true) => Ok(ExportFormatSpec::POPRAKO),

        (true, true) => Ok(ExportFormatSpec::BOTH),

        (false, false) => {
            Err(D::Error::custom("at least one export format is required"))
        }
    }
}

/// Translation format used by chapter translation HTTP inputs.
#[derive(Debug, Clone, Copy, Deserialize)]
#[cfg_attr(feature = "swagger", derive(ToSchema))]
#[serde(rename_all = "snake_case")]
pub enum ChapterTranslationFormatBody {
    /// `LabelPlus` translation format.
    LabelPlus,

    /// `Poprako` native translation format.
    Poprako,
}

impl From<ChapterTranslationFormatBody> for ChapterTranslationFormatInstr {
    // Converts the value between the use-case and wire shapes.
    fn from(value: ChapterTranslationFormatBody) -> Self {
        //
        match value {
            //
            ChapterTranslationFormatBody::LabelPlus => Self::LabelPlus,

            ChapterTranslationFormatBody::Poprako => Self::Poprako,
        }
    }
}

/// source page-content strategy selected by a chapter translation import request.
#[derive(Debug, Clone, Copy, Deserialize)]
#[cfg_attr(feature = "swagger", derive(ToSchema))]
#[serde(rename_all = "snake_case")]
pub enum ChapterTranslationImportModeBody {
    /// Preserve pages that already contain visible Units.
    Keep,

    /// Replace every page with the Units represented by the imported source.
    Overwrite,
}

impl From<ChapterTranslationImportModeBody>
    for ChapterTranslationImportModeInstr
{
    // Converts the value between the use-case and wire shapes.
    fn from(value: ChapterTranslationImportModeBody) -> Self {
        //
        match value {
            //
            ChapterTranslationImportModeBody::Keep => Self::Keep,

            ChapterTranslationImportModeBody::Overwrite => Self::Overwrite,
        }
    }
}

