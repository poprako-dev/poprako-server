/// JSON document exchanged by the `PopRaKo` translation port.
#[derive(Clone, Deserialize, Serialize)]
#[cfg_attr(feature = "swagger", derive(ToSchema))]
pub struct ChapterTranslationPortObj {
    /// Chapter identifier from the exporting chapter.
    pub chapter_id: String,
    /// Ordinal index of the chapter within its comic.
    pub chapter_index: usize,
    /// Optional subtitle from the exporting chapter.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub chapter_subtitle: Option<String>,

    /// Comic identifier from the exporting comic.
    pub comic_id: String,
    /// Comic title from the exporting comic.
    pub comic_title: String,

    /// source pages and their translation units.
    pub pages: Vec<PageSourceTranslationPortObj>,
}

impl From<ChapterTranslationPortView> for ChapterTranslationPortObj {
    // Converts the value between the use-case and wire shapes.
    fn from(value: ChapterTranslationPortView) -> Self {
        Self {
            chapter_id: value.chapter_id,
            chapter_index: value.chapter_index,
            chapter_subtitle: value.chapter_subtitle,
            comic_id: value.comic_id,
            comic_title: value.comic_title,
            pages: value
                .pages
                .into_iter()
                .map(std::convert::Into::into)
                .collect(),
        }
    }
}

impl Wire for ChapterTranslationPortView {
    // Serializable wire payload produced by this conversion.
    type Target = ChapterTranslationPortObj;

    // Converts the use-case value into its wire representation.
    fn into_wire(self) -> Self::Target {
        self.into()
    }
}

