/// Translation documents generated together by one chapter export.
#[derive(Serialize)]
#[cfg_attr(feature = "swagger", derive(ToSchema))]
pub struct ExportChapterTranslationsPayload {
    /// `LabelPlus` text, absent when that format was not selected.
    pub label_plus: Option<String>,
    /// Native `PopRaKo` document, absent when that format was not selected.
    pub poprako: Option<ChapterTranslationPortObj>,
    /// source page-to-original-filename mappings, absent unless requested.
    pub raw_idents: Option<Vec<ChapterPageSourceRawIdentPayload>>,
}

impl From<ExportChapterTranslationsVal> for ExportChapterTranslationsPayload {
    // Converts the value between the use-case and wire shapes.
    fn from(value: ExportChapterTranslationsVal) -> Self {
        Self {
            label_plus: value.label_plus,
            poprako: value.poprako.map(std::convert::Into::into),
            raw_idents: value.raw_idents.map(|item| {
                item.into_iter().map(std::convert::Into::into).collect()
            }),
        }
    }
}

impl Wire for ExportChapterTranslationsVal {
    // Serializable wire payload produced by this conversion.
    type Target = ExportChapterTranslationsPayload;

    // Converts the use-case value into its wire representation.
    fn into_wire(self) -> Self::Target {
        self.into()
    }
}

