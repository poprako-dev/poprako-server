use std::collections::BTreeMap;

use time::OffsetDateTime;
use url::Url;

use crate::key::{ObjKey, ObjKind};

/// Input required to allocate one object version.
#[derive(PartialEq, Eq)]
pub struct ObjSlotSpec<'a, K>
where
    K: ObjKind,
{
    /// Typed business identity from which the physical key is derived.
    pub dom: K::Dom,

    /// Opaque content hash.
    pub hash: &'a [u8],

    /// Media type signed into the upload capability.
    pub content_type: &'a str,

    /// Exact signed byte length.
    pub byte_len: u64,
}

/// Upload capability returned by `ObjDept`.
#[derive(PartialEq, Eq)]
pub struct ObjSlot<K>
where
    K: ObjKind,
{
    /// Allocated logical object key.
    pub key: ObjKey<K>,
    /// Signed upload URL.
    pub url: Url,
    /// Headers signed into the capability.
    pub headers: BTreeMap<String, String>,
    /// Capability expiry.
    pub expires_at: OffsetDateTime,
}

impl<K> Clone for ObjSlot<K>
where
    K: ObjKind + Clone,
    K::Id: Clone,
{
    // Clones the value when its owned identity supports cloning.
    fn clone(&self) -> Self {
        Self {
            key: self.key.clone(),
            url: self.url.clone(),
            headers: self.headers.clone(),
            expires_at: self.expires_at,
        }
    }
}

/// Storage-neutral upload capability generated by an object pool.
#[derive(Clone, PartialEq, Eq)]
pub struct ObjDeptPoolSlot {
    /// Signed upload URL.
    pub url: Url,
    /// Headers signed into the capability.
    pub headers: BTreeMap<String, String>,
    /// Capability expiry.
    pub expires_at: OffsetDateTime,
}
