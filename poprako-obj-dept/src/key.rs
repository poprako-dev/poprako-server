//! Typed object identities and immutable physical locations.

use std::borrow::Borrow;
use std::fmt::Debug;
use std::hash::Hash;

use serde::Serialize;
use serde::de::DeserializeOwned;
use serde_json::Value;

use crate::model::record::ObjKeyRecord;
use crate::rest::{ObjDeptError, ObjDeptRest};

/// Validated scalar owned by an object kind.
pub trait ObjId: Debug + Eq + Ord + Hash + Sized {
    /// Validates a scalar at an input or persistence seam.
    ///
    /// # Errors
    /// Returns an error when the text violates this scalar's contract.
    fn from_text(value: &str) -> ObjDeptRest<Self>;

    /// Validates an owned scalar, allowing adapters to retain its allocation.
    ///
    /// # Errors
    /// Returns an error when the text violates this scalar's contract.
    fn from_owned(value: String) -> ObjDeptRest<Self> {
        Self::from_text(&value)
    }

    /// Borrows its canonical storage representation.
    fn as_str(&self) -> &str;
}

/// Opaque physical location; it is never decoded into business identity.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct ObjPath(String);

impl ObjPath {
    /// Stores a location generated by the owning storage mapping.
    #[must_use]
    pub const fn new(value: String) -> Self {
        Self(value)
    }

    /// Borrows the exact bytes used by persistence and physical storage.
    #[must_use]
    pub const fn as_str(&self) -> &str {
        self.0.as_str()
    }
}

/// Defines one object kind and its one-way physical mapping.
pub trait ObjKind: Debug + Eq + Hash {
    /// Validated business identity used by the object table.
    type Id: ObjId + Borrow<str> + Into<String>;

    /// Validated suffix for this kind.
    type Ext: ObjId;

    /// Complete domain input for physical-key generation.
    type Dom: Serialize + DeserializeOwned;

    /// Borrows the stable object identity.
    fn id(value: &Self::Dom) -> &Self::Id;

    /// Borrows the validated suffix.
    fn ext(value: &Self::Dom) -> &Self::Ext;

    /// Builds an immutable physical location for one allocated generation.
    fn forward(value: &Self::Dom, ver: u32) -> ObjPath;

    /// Validates a batch of identities before constructing an operation.
    ///
    /// # Errors
    /// Returns an error when any identity is invalid for this kind.
    fn ids<T>(values: &[T]) -> ObjDeptRest<Vec<Self::Id>>
    where
        T: AsRef<str>,
    {
        //
        values
            .iter()
            .map(|value| Self::Id::from_text(value.as_ref()))
            .collect()
    }
}

/// Static durable-task binding emitted by the object manifest.
pub trait ObjRegistration: ObjKind {
    /// Durable topic belonging to this exact object kind.
    const TOPIC: &'static str;
}

/// Client-addressable generation that belongs to one object kind.
///
/// ```compile_fail,E0308
/// use poprako_obj_dept::key::{ObjGen, ObjKind};
/// fn confirm<K: ObjKind, L: ObjKind>(id: L::Id) -> ObjGen<K> {
///     ObjGen::<K>::new(id, 1)
/// }
/// ```
///
/// ```
/// use poprako_obj_dept::key::{ObjGen, ObjKind};
/// fn confirm<K: ObjKind>(id: K::Id) -> ObjGen<K> {
///     ObjGen::<K>::new(id, 1)
/// }
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct ObjGen<K>
where
    K: ObjKind,
{
    /// Validated stable business identifier.
    id: K::Id,

    /// Exact allocated version.
    ver: u32,
}

impl<K> ObjGen<K>
where
    K: ObjKind,
{
    /// Selects an exact generation using an already validated identity.
    pub const fn new(id: K::Id, ver: u32) -> Self {
        Self { id, ver }
    }

    /// Borrows the business identity.
    pub const fn id(&self) -> &K::Id {
        &self.id
    }

    /// Returns the selected generation.
    pub const fn ver(&self) -> u32 {
        self.ver
    }
}

/// Immutable identity and physical snapshot for one exact object generation.
///
/// A key cannot change its object kind or independently replace its location.
///
/// ```compile_fail,E0308
/// use poprako_obj_dept::key::{ObjKey, ObjKind};
/// fn retag<K: ObjKind, L: ObjKind>(key: ObjKey<K>) -> ObjKey<L> {
///     key
/// }
/// ```
///
/// ```compile_fail,E0616
/// use poprako_obj_dept::key::{ObjKey, ObjKind};
/// fn mutate<K: ObjKind>(mut key: ObjKey<K>) {
///     key.ver = 99;
/// }
/// ```
///
/// Domain input must belong to the selected kind.
///
/// ```compile_fail,E0308
/// use poprako_obj_dept::key::{ObjKey, ObjKind};
/// fn allocate<K: ObjKind, L: ObjKind>(dom: &L::Dom) -> ObjKey<K> {
///     ObjKey::<K>::new(dom, 1)
/// }
/// ```
///
/// ```
/// use poprako_obj_dept::key::{ObjKey, ObjKind};
/// fn allocate<K: ObjKind>(dom: &K::Dom) -> poprako_obj_dept::rest::ObjDeptRest<ObjKey<K>>
/// where
///     K::Id: Clone,
/// {
///     ObjKey::<K>::new(dom, 1)
/// }
/// ```
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct ObjKey<K>
where
    K: ObjKind,
{
    /// Validated stable business identifier.
    id: K::Id,

    /// Exact allocated version.
    ver: u32,
    /// Immutable physical storage location.
    image: ObjPath,
    /// Validated construction data retained for persistence.
    domain: Value,
    /// Canonical suffix of the validated construction data.
    ext: String,
}

impl<K> ObjKey<K>
where
    K: ObjKind,
{
    /// Generates a key from validated domain input and one allocated version.
    ///
    /// # Errors
    /// Returns an error when construction data cannot be serialized.
    pub fn new(dom: &K::Dom, ver: u32) -> ObjDeptRest<Self>
    where
        K::Id: Clone,
    {
        //
        let domain = serde_json::to_value(dom).map_err(|source| {
            ObjDeptError::Unrecoverable {
                message: [
                    "invalid object construction data: ",
                    &source.to_string(),
                ]
                .concat(),
            }
        })?;

        Ok(Self {
            id: K::id(dom).clone(),
            ver,
            image: K::forward(dom, ver),
            domain,
            ext: K::ext(dom).as_str().into(),
        })
    }

    /// Validates persisted construction data and generates its canonical location.
    ///
    /// # Errors
    /// Returns an error for invalid fields or an inconsistent owner identity.
    #[doc(hidden)]
    pub fn from_record(record: ObjKeyRecord) -> ObjDeptRest<Self> {
        //
        let dom = serde_json::from_value::<K::Dom>(record.domain.clone())
            .map_err(|source| ObjDeptError::Unrecoverable {
                message: [
                    "invalid persisted object domain: ",
                    &source.to_string(),
                ]
                .concat(),
            })?;

        let id = K::Id::from_owned(record.id).map_err(|_| {
            ObjDeptError::Unrecoverable {
                message: "invalid persisted object identity".into(),
            }
        })?;

        if K::id(&dom) != &id {
            //
            return Err(ObjDeptError::Unrecoverable {
                message: "object domain differs from persisted identity".into(),
            });
        }

        Ok(Self {
            id,
            ver: record.ver,
            image: K::forward(&dom, record.ver),
            domain: record.domain,
            ext: K::ext(&dom).as_str().into(),
        })
    }

    /// Projects the validated construction data for durable storage.
    #[doc(hidden)]
    pub fn to_record(&self) -> ObjKeyRecord {
        ObjKeyRecord {
            id: self.id.as_str().into(),
            ver: self.ver,
            domain: self.domain.clone(),
        }
    }

    /// Borrows the validated data used to generate the physical location.
    #[doc(hidden)]
    pub const fn domain(&self) -> &Value {
        &self.domain
    }

    /// Borrows the suffix validated with the construction data.
    pub fn ext(&self) -> &str {
        &self.ext
    }

    /// Borrows the business identity.
    pub const fn id(&self) -> &K::Id {
        &self.id
    }

    /// Returns the exact allocated generation.
    pub const fn ver(&self) -> u32 {
        self.ver
    }

    /// Borrows the immutable physical location.
    pub const fn image(&self) -> &ObjPath {
        &self.image
    }

    /// Returns the client-addressable generation without a physical location.
    pub fn gen_no(&self) -> ObjGen<K>
    where
        K::Id: Clone,
    {
        ObjGen::new(self.id.clone(), self.ver)
    }
}
